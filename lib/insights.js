export function getPublishedInsights() {
  return insights.filter((item) => item.status === 'published');
}

export function getInsight(slug) {
  return getPublishedInsights().find((item) => item.slug === slug);
}

export function getAuthor(slug) {
  return authors[slug];
}

export function getRelatedInsights(insight, limit = 3) {
  if (!insight) return [];
  const published = getPublishedInsights().filter((item) => item.slug !== insight.slug);

  if (insight.related?.length) {
    const explicit = insight.related
      .map((slug) => published.find((item) => item.slug === slug))
      .filter(Boolean);
    if (explicit.length) return explicit.slice(0, limit);
  }

  return published
    .filter(
      (item) =>
        item.category === insight.category ||
        item.secondaryCategories?.includes(insight.category) ||
        insight.secondaryCategories?.includes(item.category)
    )
    .slice(0, limit);
}
